; intrinsic_resolve(table*, request*)
; Normal signature matching occurs first. Runtime-special semantics are returned
; as explicit metadata only after a unique receiver/name/arity match.
NEBOC_ABI_FUNCTION neboc_intrinsic_resolve
 push rbx
 push r12
 push r13
 push r14
 push r15
 mov r12,rdi
 mov r13,rsi
 test r12,r12
 jz .bad_argument
 test r13,r13
 jz .bad_argument
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_OUT_INTRINSIC_ID_OFFSET],0
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_OUT_RETURN_TYPE_OFFSET],0
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_OUT_EFFECT_ID_OFFSET],0
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_OUT_CONCURRENCY_OFFSET],0
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_OUT_RUNTIME_CONTRACT_OFFSET],0
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_OUT_FLAGS_OFFSET],0
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_ERROR_CODE_OFFSET],NEBOC_INTRINSIC_ERROR_NONE
 cmp qword [r12+NEBOC_INTRINSIC_TABLE_STATE_OFFSET],NEBOC_INTRINSIC_TABLE_STATE_FROZEN
 jne .bad_table
 mov rbx,[r12+NEBOC_INTRINSIC_TABLE_DATA_OFFSET]
 test rbx,rbx
 jz .bad_table
 xor r14d,r14d
 xor r15d,r15d
.search:
 cmp r14,[r12+NEBOC_INTRINSIC_TABLE_COUNT_OFFSET]
 jae .search_done
 mov rax,r14
 imul rax,NEBOC_INTRINSIC_ENTRY_SIZE
 add rax,rbx
 cmp qword [rax+NEBOC_INTRINSIC_ENTRY_NAME_ID_OFFSET],0
 je .next
 mov rcx,[r13+NEBOC_INTRINSIC_REQUEST_NAME_ID_OFFSET]
 cmp [rax+NEBOC_INTRINSIC_ENTRY_NAME_ID_OFFSET],rcx
 jne .next
 mov rcx,[r13+NEBOC_INTRINSIC_REQUEST_RECEIVER_TYPE_OFFSET]
 cmp [rax+NEBOC_INTRINSIC_ENTRY_RECEIVER_TYPE_OFFSET],rcx
 jne .next
 mov rcx,[r13+NEBOC_INTRINSIC_REQUEST_POSITIONAL_COUNT_OFFSET]
 cmp [rax+NEBOC_INTRINSIC_ENTRY_POSITIONAL_COUNT_OFFSET],rcx
 jne .next
 test r15,r15
 jnz .ambiguous
 mov r15,rax
.next:
 inc r14
 jmp .search
.search_done:
 test r15,r15
 jz .no_match
 mov rax,[r13+NEBOC_INTRINSIC_REQUEST_BEHAVIOR_MASK_OFFSET]
 mov rcx,[r15+NEBOC_INTRINSIC_ENTRY_ACCEPTED_BEHAVIOR_MASK_OFFSET]
 not rcx
 and rax,rcx
 test rax,rax
 jnz .unsupported_behavior
 mov rax,[r15+NEBOC_INTRINSIC_ENTRY_ID_OFFSET]
 mov [r13+NEBOC_INTRINSIC_REQUEST_OUT_INTRINSIC_ID_OFFSET],rax
 mov rax,[r15+NEBOC_INTRINSIC_ENTRY_RETURN_TYPE_OFFSET]
 mov [r13+NEBOC_INTRINSIC_REQUEST_OUT_RETURN_TYPE_OFFSET],rax
 mov rax,[r15+NEBOC_INTRINSIC_ENTRY_EFFECT_ID_OFFSET]
 mov [r13+NEBOC_INTRINSIC_REQUEST_OUT_EFFECT_ID_OFFSET],rax
 mov rax,[r15+NEBOC_INTRINSIC_ENTRY_CONCURRENCY_OFFSET]
 mov [r13+NEBOC_INTRINSIC_REQUEST_OUT_CONCURRENCY_OFFSET],rax
 mov rax,[r15+NEBOC_INTRINSIC_ENTRY_RUNTIME_CONTRACT_ID_OFFSET]
 mov [r13+NEBOC_INTRINSIC_REQUEST_OUT_RUNTIME_CONTRACT_OFFSET],rax
 mov rax,[r15+NEBOC_INTRINSIC_ENTRY_FLAGS_OFFSET]
 mov [r13+NEBOC_INTRINSIC_REQUEST_OUT_FLAGS_OFFSET],rax
 xor eax,eax
 jmp .done
.no_match:
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_ERROR_CODE_OFFSET],NEBOC_INTRINSIC_ERROR_NO_MATCH
 mov eax,NEBOC_STATUS_INVALID_SOURCE
 jmp .done
.unsupported_behavior:
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_ERROR_CODE_OFFSET],NEBOC_INTRINSIC_ERROR_UNSUPPORTED_BEHAVIOR
 mov eax,NEBOC_STATUS_INVALID_SOURCE
 jmp .done
.ambiguous:
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_ERROR_CODE_OFFSET],NEBOC_INTRINSIC_ERROR_AMBIGUOUS
 mov eax,NEBOC_STATUS_INTERNAL_ERROR
 jmp .done
.bad_table:
 mov qword [r13+NEBOC_INTRINSIC_REQUEST_ERROR_CODE_OFFSET],NEBOC_INTRINSIC_ERROR_BAD_TABLE
 mov eax,NEBOC_STATUS_INVALID_ARGUMENT
 jmp .done
.bad_argument:
 mov eax,NEBOC_STATUS_INVALID_ARGUMENT
.done:
 pop r15
 pop r14
 pop r13
 pop r12
 pop rbx
 cld
 ret

