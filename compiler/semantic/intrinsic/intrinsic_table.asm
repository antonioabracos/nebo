; intrinsic_table_freeze(table*)
NEBOC_ABI_FUNCTION neboc_intrinsic_table_freeze
 push rbx
 push r12
 push r13
 push r14
 mov r12,rdi
 test r12,r12
 jz .freeze_invalid
 cmp qword [r12+NEBOC_INTRINSIC_TABLE_STATE_OFFSET],NEBOC_INTRINSIC_TABLE_STATE_MUTABLE
 jne .freeze_invalid
 cmp qword [r12+NEBOC_INTRINSIC_TABLE_COUNT_OFFSET],NEBOC_INTRINSIC_COUNT
 jne .freeze_invalid
 cmp qword [r12+NEBOC_INTRINSIC_TABLE_RUNTIME_VERSION_OFFSET],NEBOC_RUNTIME_CONTRACT_VERSION_V0_1
 jne .freeze_invalid
 mov r13,[r12+NEBOC_INTRINSIC_TABLE_DATA_OFFSET]
 test r13,r13
 jz .freeze_invalid
 mov ebx,NEBOC_INTRINSIC_HASH_FNV1A32_OFFSET_BASIS
 xor r14d,r14d
.entry_loop:
 cmp r14,NEBOC_INTRINSIC_COUNT
 jae .freeze_done_hash
 mov rax,r14
 imul rax,NEBOC_INTRINSIC_ENTRY_SIZE
 add rax,r13
 mov ecx,11
 mov r8,rax
 mov r9d,NEBOC_INTRINSIC_HASH_FNV1A32_OFFSET_BASIS
.entry_hash_loop:
 mov rdx,[r8]
 push rcx
 mov ecx,8
.entry_hash_bytes:
 movzx r10d,dl
 xor r9d,r10d
 imul r9d,r9d,NEBOC_INTRINSIC_HASH_FNV1A32_PRIME
 shr rdx,8
 dec ecx
 jnz .entry_hash_bytes
 pop rcx
 add r8,8
 dec ecx
 jnz .entry_hash_loop
 mov [rax+NEBOC_INTRINSIC_ENTRY_SIGNATURE_HASH_OFFSET],r9
 xor ebx,r9d
 imul ebx,ebx,NEBOC_INTRINSIC_HASH_FNV1A32_PRIME
 inc r14
 jmp .entry_loop
.freeze_done_hash:
 mov [r12+NEBOC_INTRINSIC_TABLE_HASH_OFFSET],rbx
 mov qword [r12+NEBOC_INTRINSIC_TABLE_STATE_OFFSET],NEBOC_INTRINSIC_TABLE_STATE_FROZEN
 xor eax,eax
 jmp .freeze_done
.freeze_invalid:
 mov eax,NEBOC_STATUS_INVALID_ARGUMENT
.freeze_done:
 pop r14
 pop r13
 pop r12
 pop rbx
