; core_arithmetic_registry_table() -> RAX=entries, EDX=count, ECX=schema.
NEBOC_ABI_FUNCTION neboc_core_arithmetic_registry_table
 lea rax,[rel core_arithmetic_entries]
 mov edx,NEBOC_CORE_ARITHMETIC_REGISTRY_ENTRY_COUNT
 mov ecx,NEBOC_CORE_ARITHMETIC_REGISTRY_SCHEMA_VERSION
 ret

; core_arithmetic_registry_lookup(id) -> RAX=entry or zero.
NEBOC_ABI_FUNCTION neboc_core_arithmetic_registry_lookup
 lea rax,[rel core_arithmetic_entries]
 mov ecx,NEBOC_CORE_ARITHMETIC_REGISTRY_ENTRY_COUNT
.id_loop:
 cmp [rax+NEBOC_CORE_ARITHMETIC_ENTRY_ID_OFFSET],rdi
 je .found
 add rax,NEBOC_CORE_ARITHMETIC_ENTRY_SIZE
 dec ecx
 jnz .id_loop
 xor eax,eax
.found:
 ret

; core_arithmetic_registry_resolve(token, follow-token, fixity, contexts)
; returns RAX=entry and EDX=stable Registry ID, or zeroes both on rejection.
NEBOC_ABI_FUNCTION neboc_core_arithmetic_registry_resolve
 lea rax,[rel core_arithmetic_entries]
 mov r8d,NEBOC_CORE_ARITHMETIC_REGISTRY_ENTRY_COUNT
.resolve_loop:
 cmp [rax+NEBOC_CORE_ARITHMETIC_ENTRY_TOKEN_OFFSET],rdi
 jne .next
 cmp [rax+NEBOC_CORE_ARITHMETIC_ENTRY_FOLLOW_TOKEN_OFFSET],rsi
 jne .next
 cmp [rax+NEBOC_CORE_ARITHMETIC_ENTRY_FIXITY_OFFSET],rdx
 jne .next
 mov r9,[rax+NEBOC_CORE_ARITHMETIC_ENTRY_CONTEXTS_OFFSET]
 and r9,rcx
 jz .next
 cmp qword [rax+NEBOC_CORE_ARITHMETIC_ENTRY_STATE_OFFSET],NEBOC_OPERATOR_STATE_ACTIVE_CURRENT
 jne .next
 mov edx,[rax+NEBOC_CORE_ARITHMETIC_ENTRY_ID_OFFSET]
 ret
.next:
 add rax,NEBOC_CORE_ARITHMETIC_ENTRY_SIZE
 dec r8d
 jnz .resolve_loop
 xor eax,eax
 xor edx,edx
 ret

