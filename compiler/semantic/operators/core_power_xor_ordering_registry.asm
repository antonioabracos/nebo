NEBOC_ABI_FUNCTION neboc_core_pxo_registry_table
 lea rax,[rel core_pxo_entries]
 mov edx,NEBOC_CORE_PXO_REGISTRY_ENTRY_COUNT
 mov ecx,NEBOC_CORE_PXO_REGISTRY_SCHEMA_VERSION
 ret

NEBOC_ABI_FUNCTION neboc_core_pxo_registry_lookup
 lea rax,[rel core_pxo_entries]
 mov ecx,NEBOC_CORE_PXO_REGISTRY_ENTRY_COUNT
.loop:
 cmp [rax+NEBOC_CORE_PXO_ENTRY_ID_OFFSET],rdi
 je .found
 add rax,NEBOC_CORE_PXO_ENTRY_SIZE
 dec ecx
 jnz .loop
 xor eax,eax
.found:
 ret

; resolve(token, fixity, contexts) -> RAX=entry, EDX=stable ID or zeroes.
NEBOC_ABI_FUNCTION neboc_core_pxo_registry_resolve
 lea rax,[rel core_pxo_entries]
 mov r8d,NEBOC_CORE_PXO_REGISTRY_ENTRY_COUNT
.resolve:
 cmp [rax+NEBOC_CORE_PXO_ENTRY_TOKEN_OFFSET],rdi
 jne .next
 cmp [rax+NEBOC_CORE_PXO_ENTRY_FIXITY_OFFSET],rsi
 jne .next
 mov r9,[rax+NEBOC_CORE_PXO_ENTRY_CONTEXTS_OFFSET]
 and r9,rdx
 jz .next
 cmp qword [rax+NEBOC_CORE_PXO_ENTRY_STATE_OFFSET],NEBOC_OPERATOR_STATE_ACTIVE_CURRENT
 jne .next
 mov edx,[rax+NEBOC_CORE_PXO_ENTRY_ID_OFFSET]
 ret
.next:
 add rax,NEBOC_CORE_PXO_ENTRY_SIZE
 dec r8d
 jnz .resolve
 xor eax,eax
 xor edx,edx
 ret

