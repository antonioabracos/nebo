section .text
NEBOC_ABI_FUNCTION neboc_unicode_alias_registry_table
 lea rax,[rel unicode_alias_entries]
 mov edx,NEBOC_UNICODE_ALIAS_REGISTRY_ENTRY_COUNT
 mov ecx,NEBOC_UNICODE_ALIAS_REGISTRY_SCHEMA_VERSION
 ret

NEBOC_ABI_FUNCTION neboc_unicode_alias_registry_lookup
 lea rax,[rel unicode_alias_entries]
 mov ecx,NEBOC_UNICODE_ALIAS_REGISTRY_ENTRY_COUNT
.lookup:
 cmp [rax+NEBOC_UNICODE_ALIAS_ENTRY_ID_OFFSET],rdi
 je .found
 add rax,NEBOC_UNICODE_ALIAS_ENTRY_SIZE
 dec ecx
 jnz .lookup
 xor eax,eax
.found:
 ret

; resolve(codepoint, canonical token, source fixity) -> RAX=active row,
; EDX=global alias ID, ECX=canonical CORE ID; zeroes on any mismatch.
NEBOC_ABI_FUNCTION neboc_unicode_alias_registry_resolve
 lea rax,[rel unicode_alias_entries]
 mov r8d,NEBOC_UNICODE_ALIAS_REGISTRY_ENTRY_COUNT
.resolve:
 cmp [rax+NEBOC_UNICODE_ALIAS_ENTRY_CODEPOINT_OFFSET],rdi
 jne .next
 cmp [rax+NEBOC_UNICODE_ALIAS_ENTRY_TOKEN_OFFSET],rsi
 jne .next
 cmp qword [rax+NEBOC_UNICODE_ALIAS_ENTRY_STATE_OFFSET],NEBOC_OPERATOR_STATE_ACTIVE_CURRENT
 jne .next
 cmp rdx,NEBOC_OPERATOR_FIXITY_PREFIX
 je .prefix
 cmp rdx,NEBOC_OPERATOR_FIXITY_INFIX
 jne .next
 test qword [rax+NEBOC_UNICODE_ALIAS_ENTRY_FIXITY_MASK_OFFSET],NEBOC_UNICODE_ALIAS_FIXITY_INFIX
 jz .next
 mov ecx,[rax+NEBOC_UNICODE_ALIAS_ENTRY_INFIX_CORE_ID_OFFSET]
 jmp .resolved
.prefix:
 test qword [rax+NEBOC_UNICODE_ALIAS_ENTRY_FIXITY_MASK_OFFSET],NEBOC_UNICODE_ALIAS_FIXITY_PREFIX
 jz .next
 mov ecx,[rax+NEBOC_UNICODE_ALIAS_ENTRY_PREFIX_CORE_ID_OFFSET]
.resolved:
 test ecx,ecx
 jz .next
 mov edx,[rax+NEBOC_UNICODE_ALIAS_ENTRY_ID_OFFSET]
 ret
.next:
 add rax,NEBOC_UNICODE_ALIAS_ENTRY_SIZE
 dec r8d
 jnz .resolve
 xor eax,eax
 xor edx,edx
 xor ecx,ecx
 ret

