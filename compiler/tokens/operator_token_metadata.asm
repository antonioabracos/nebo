; atom_metadata(atom_index, requested_context) -> RAX=record or zero,
; EDX=1 exactly when at least one requested context is allowed.
NEBOC_ABI_FUNCTION neboc_operator_atom_metadata
 cmp rdi,NEBOC_OPERATOR_REGISTRY_LEXEME_COUNT
 jae .missing
 imul rdi,OPERATOR_ATOM_META_SIZE
 lea rax,[rel atom_metadata]
 add rax,rdi
 xor edx,edx
 test [rax+OPERATOR_ATOM_META_CONTEXTS_OFFSET],rsi
 setnz dl
 ret
.missing:
 xor eax,eax
 xor edx,edx
 ret

; Return the stable record ABI to bounded tooling consumers.
NEBOC_ABI_FUNCTION neboc_operator_atom_metadata_abi
 mov eax,OPERATOR_ATOM_META_SIZE
 mov edx,NEBOC_OPERATOR_REGISTRY_LEXEME_COUNT
 mov ecx,NEBOC_OPERATOR_REGISTRY_SCHEMA_VERSION
 ret

